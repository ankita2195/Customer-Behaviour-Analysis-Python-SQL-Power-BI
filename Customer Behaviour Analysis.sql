-- BUSINESS QUESTIONS

-- 1. Which category generates the highest revenue?
SELECT category, ROUND(SUM(purchase_amount),2) revenue, ROUND(AVG(purchase_amount),2) avg_rev
FROM customers
GROUP BY category
ORDER BY revenue DESC
LIMIT 1;
	# Electronics contributes the highest revenue mainly due to its higher-priced products, resulting in the highest Average Order Value among all categories.

-- 2. Are discounts actually increasing the purchase value?
SELECT discount_applied, 
	COUNT(*) customer_count,
	ROUND(SUM(purchase_amount),2) purchase_value, 
    ROUND(AVG(purchase_amount),2) avg_purchase_value    
FROM customers
GROUP BY discount_applied;
	# Customers who received discounts showed a higher average purchase value.
	# This suggests that discounts are encouraging our customers to buy more.

-- 3. What is the total revenue generated by male and female customers?
SELECT gender, 
COUNT(*) customer_count,
ROUND(SUM(purchase_amount),2) revenue,
ROUND(AVG(purchase_amount),2) avg_purchase_value 
FROM customers
GROUP BY gender
ORDER BY revenue DESC;
	# Male customers have highest overall revenue due to a large customer base but have the least average purchase value. 
	# The “Other” category records the highest average purchase value, although the smaller customer count suggests this segment may represent a niche but high-spending customer group.
	# Since female customers and the “Other” category show higher average purchase values, the business should consider targeted marketing campaigns and personalized product recommendations for these segments to maximize high-value sales opportunities.

-- 4. Which customer used a discount but still spent more than the average purchase amount?
