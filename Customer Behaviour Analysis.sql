-- 11. What are the top 3 most purchased products within each category?
WITH ranked_items AS (
	SELECT 
		category, 
        item_purchased products, 
        RANK() OVER (PARTITION BY category ORDER BY COUNT(item_purchased) DESC) rnk
	FROM customers
	GROUP BY category, products
)
SELECT 
	category, GROUP_CONCAT(products SEPARATOR " ,") products
FROM ranked_items
WHERE rnk <= 3
GROUP BY category;
	# Identifying the top products would help in inventory optimization and increasing sales through best sellers.

-- 12. What is the revenue contribution of each age group?
SELECT
	CASE WHEN age BETWEEN 18 AND 30 THEN "18-30"
		 WHEN age BETWEEN 31 AND 45 THEN "31-45"
         WHEN age BETWEEN 46 AND 60 THEN "45-60"
		 ELSE "60+"
	END AS age_group,
    ROUND(SUM(purchase_amount),2) revenue,
    COUNT(customer_id) customer_count,
    ROUND(AVG(purchase_amount),2) avg_purchase_value
    FROM customers
GROUP BY age_group
ORDER BY age_group;
	# Customers aged 45–60 generate the highest overall revenue due to a larger customer base and strong purchasing activity.
	# However, customers from the age-group 60+ have the highest average purchase value even after being smallest in count indicating they tend to spend more per transaction compared to other age groups.