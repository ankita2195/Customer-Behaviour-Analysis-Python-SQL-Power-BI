-- 9. Segment customer into new, returning and loyal based on their total number of previous purchases, and show the count of each segment.
 SELECT
	"Loyal" customer_segment,
	SUM(CASE WHEN previous_purchases > 15 THEN 1 ELSE 0 END) customer_count
FROM customers
UNION ALL
SELECT
	"Returning" customer_segment,
	SUM(CASE WHEN previous_purchases <= 15 AND previous_purchases > 0 THEN 1 ELSE 0 END) customer_count
FROM customers
UNION ALL
SELECT
	"New" customer_segment,
	SUM(CASE WHEN previous_purchases = 0 THEN 1 ELSE 0 END) customer_count
FROM customers;
	# About 60% of the customers are loyal reflecting a strong repeat purchase behaviour.
	# 11% new customers highlight an opportunity to strengthen customer acquisition strategies and expand customer base.

